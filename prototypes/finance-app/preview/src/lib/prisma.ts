async function initialize(): Promise<PrismaClient> {
  const root = process.env.FINANCE_LAB_PROJECT_DIR;
  if (process.env.NODE_ENV !== "development" || process.env.FINANCE_LAB_ONLY !== "disposable-in-memory" || !root) {
    throw new Error("The finance lab can only run in its disposable development copy.");
  }

  const pg = new PGlite();
  for (const file of MIGRATION_FILES) {
    await pg.exec(await readFile(join(root, file), "utf8"));
  }

  await pg.exec(`
    CREATE TYPE "AuthAttemptResult" AS ENUM ('SUCCESS','FAILED','THROTTLED','PASSWORD_CHANGE_SUCCESS','PASSWORD_CHANGE_FAILED','PASSWORD_RESET');
    CREATE TABLE auth_sessions (
      id VARCHAR(64) PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE login_attempts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      identifier_hash CHAR(64) NOT NULL,
      user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
      result "AuthAttemptResult" NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE login_throttles (
      key CHAR(64) PRIMARY KEY,
      attempts INT NOT NULL DEFAULT 0,
      window_started_at TIMESTAMPTZ NOT NULL,
      locked_until TIMESTAMPTZ,
      updated_at TIMESTAMPTZ NOT NULL
    );
    CREATE TABLE invoices (
      id BIGSERIAL PRIMARY KEY,
      invoice_no VARCHAR(24) UNIQUE NOT NULL,
      branch_id BIGINT NOT NULL,
      warehouse_id BIGINT NOT NULL,
      customer_id BIGINT,
      subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
      discount NUMERIC(14,2) NOT NULL DEFAULT 0,
      taxable_base NUMERIC(14,2) NOT NULL DEFAULT 0,
      tax_total NUMERIC(14,2) NOT NULL DEFAULT 0,
      total NUMERIC(14,2) NOT NULL DEFAULT 0,
      status VARCHAR(12) NOT NULL DEFAULT 'DRAFT',
      created_by BIGINT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE invoice_items (
      id BIGSERIAL PRIMARY KEY,
      invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
      product_id BIGINT,
      description VARCHAR(220) NOT NULL,
      qty NUMERIC(10,2) NOT NULL,
      unit_price NUMERIC(14,2) NOT NULL,
      tax_rate_id INTEGER,
      tax_amount NUMERIC(14,2) NOT NULL DEFAULT 0
    );
    CREATE TABLE invoice_taxes (
      id BIGSERIAL PRIMARY KEY,
      invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
      tax_rate_id INTEGER NOT NULL REFERENCES tax_rates(id),
      base_amount NUMERIC(14,2) NOT NULL,
      tax_amount NUMERIC(14,2) NOT NULL,
      sequence INTEGER NOT NULL DEFAULT 1
    );

    UPDATE branches SET code='ARH', name_ar='فرع العريش', city='العريش', invoice_prefix='ARH' WHERE id=1;
    UPDATE branches SET code='SHZ', name_ar='فرع الشيخ زويد', city='الشيخ زويد', invoice_prefix='SHZ' WHERE id=2;
    INSERT INTO branches(id,code,name_ar,city,invoice_prefix,is_active) VALUES
      (3,'BID','فرع بئر العبد','بئر العبد','BID',TRUE),
      (4,'STP','فرع تجريبي موقوف','رفح','STP',FALSE);
    SELECT setval(pg_get_serial_sequence('branches','id'),4,true);

    UPDATE warehouses SET code='W-ARH', name_ar='مستودع العريش', is_default=TRUE WHERE id=1;
    UPDATE warehouses SET code='W-SHZ', name_ar='مستودع الشيخ زويد', is_default=TRUE WHERE id=2;
    INSERT INTO warehouses(id,branch_id,code,name_ar,is_default,is_active) VALUES
      (4,3,'W-BID','مستودع بئر العبد',TRUE,TRUE),
      (5,4,'W-STP','مستودع الفرع الموقوف',TRUE,FALSE);
    SELECT setval(pg_get_serial_sequence('warehouses','id'),5,true);

    INSERT INTO tax_rates(code,name_ar,rate,kind,is_default,is_active,effective_from) VALUES
      ('VAT5','ضريبة جدول 5%',5,'SCHEDULE',TRUE,TRUE,'2020-01-01'),
      ('EXEMPT','معفى من الضريبة',0,'EXEMPT',FALSE,TRUE,'2020-01-01')
    ON CONFLICT (code) DO NOTHING;

    UPDATE expense_categories SET code='RENT', name_ar='إيجار ومرافق' WHERE id=1;
    UPDATE expense_categories SET code='SUPPLIES', name_ar='مستلزمات طبية وتشغيل' WHERE id=2;
    UPDATE expense_categories SET code='TRANS', name_ar='انتقالات وشحن' WHERE id=3;

    UPDATE products SET name_ar='سماعة خلف الأذن رقمية', sale_price=6500, purchase_cost=4100 WHERE id=1;
    UPDATE products SET name_ar='بطاريات سماعات طبية', sale_price=120, purchase_cost=55, is_active=TRUE WHERE id=2;
    UPDATE products SET name_ar='جلسة برمجة وصيانة', sale_price=350, is_active=TRUE WHERE id=3;
    INSERT INTO stock_levels(warehouse_id,product_id,qty_on_hand,avg_cost) VALUES
      (1,2,48,55),(2,2,32,55),(4,2,20,55)
    ON CONFLICT (warehouse_id,product_id) DO UPDATE SET qty_on_hand=EXCLUDED.qty_on_hand, avg_cost=EXCLUDED.avg_cost;

    UPDATE users SET full_name='أحمد المدير (تجريبي)' WHERE id=1;
    UPDATE users SET full_name='محمود المحاسب (تجريبي)' WHERE id=2;
    UPDATE users SET full_name='إبراهيم حسن' WHERE id=3;
    INSERT INTO users(id,branch_id,role_code,full_name,email,password_hash,status,must_change_password) VALUES
      (5,2,'CS_AGENT','سارة علي','staff2@example.test','placeholder','ACTIVE',FALSE),
      (6,3,'CS_AGENT','خالد منصور','staff3@example.test','placeholder','ACTIVE',FALSE),
      (7,4,'CS_AGENT','موظف الفرع الموقوف','staff-stop@example.test','placeholder','ACTIVE',FALSE);
    SELECT setval(pg_get_serial_sequence('users','id'),7,true);
  `);

  const password = await bcrypt.hash("DemoOnly-2026!", 10);
  await pg.query("UPDATE users SET password_hash=$1, must_change_password=false", [password]);

  const client = new TestClient({ adapter: new PrismaPGlite(pg) as never }) as unknown as PrismaClient;
  const fdb: FinanceDatabase = {
    serializable: async (work) => {
      try {
        return await client.$transaction((tx) => work(financePort(tx)), { isolationLevel: "Serializable", maxWait: 5000, timeout: 20000 });
      } catch (error) {
        return sqlError(error);
      }
    },
  };

  const today = cairoDate();
  const openingDate = "2026-10-01";
  const vault1 = await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "1", kind: "VAULT", holderId: null, openingAmount: "34200", openingDate, counted: true }, today);
  await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "1", kind: "CUSTODY", holderId: "3", openingAmount: "1000", openingDate, counted: true }, today);
  await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "2", kind: "VAULT", holderId: null, openingAmount: "12800", openingDate, counted: true }, today);
  const custody2 = await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "2", kind: "CUSTODY", holderId: "5", openingAmount: "800", openingDate, counted: true }, today);
  await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "3", kind: "VAULT", holderId: null, openingAmount: "8450", openingDate, counted: true }, today);
  await openAccount(fdb, "1", { requestId: randomUUID(), branchId: "3", kind: "CUSTODY", holderId: "6", openingAmount: "600", openingDate, counted: true }, today);

  // Seed fictional catalog sales across the three active branches so custody & sales cards show live figures.
  const catalog = await loadSalesCatalog(client);
  const batteryType = catalog[0]?.types[0];
  const moldType = catalog[1]?.types[0];
  if (batteryType) {
    await createCatalogSale(client, 3n, {
      requestId: randomUUID(),
      branchId: "1",
      customerName: "عميل تجريبي — العريش",
      customerPhone: "01001112233",
      discount: "0",
      initialPayment: "2450",
      method: "CASH",
      lines: [{ typeId: batteryType.id, quantity: "5", unitPrice: "490", details: batteryType.fields.map((f) => ({ key: f.key, value: "تجريبي" })) }],
    });
    await createCatalogSale(client, 5n, {
      requestId: randomUUID(),
      branchId: "2",
      customerName: "عميل تجريبي — الشيخ زويد",
      customerPhone: "01002223344",
      discount: "0",
      initialPayment: "1880",
      method: "CASH",
      lines: [{ typeId: batteryType.id, quantity: "4", unitPrice: "470", details: batteryType.fields.map((f) => ({ key: f.key, value: "تجريبي" })) }],
    });
  }
  if (moldType) {
    await createCatalogSale(client, 6n, {
      requestId: randomUUID(),
      branchId: "3",
      customerName: "عميل تجريبي — بئر العبد",
      customerPhone: "01003334455",
      discount: "0",
      initialPayment: "945",
      method: "CASH",
      lines: [{ typeId: moldType.id, quantity: "1", unitPrice: "945", details: moldType.fields.map((f) => ({ key: f.key, value: "قالب أذن يمنى" })) }],
    });
  }

  // Employee cash expense (deducted from expected cash on hand), plus pending items for Manager review.
  const staffPaid = await createExpense(fdb, "3", {
    requestId: randomUUID(), branchId: "1", categoryId: "3", amount: "300", expenseDate: today,
    description: "شحن قطع غيار للفرع (تجريبي)", beneficiary: "شركة شحن تجريبية", documentNumber: "", taxAmount: "",
  });
  await approveExpense(fdb, "1", { requestId: randomUUID(), expenseId: staffPaid.id, expectedRevision: "1" });
  await payExpense(fdb, "3", {
    requestId: randomUUID(), expenseId: staffPaid.id, expectedRevision: "2", method: "CASH",
    accountId: "", paymentDate: today, actuallyPaid: true, expectedBalance: "", negativeAcknowledged: false, source: "HOLDER_CASH",
  }, today);

  // Pending expenses awaiting approval + approved expense awaiting payment + open count + open settlement.
  await createExpense(fdb, "5", {
    requestId: randomUUID(), branchId: "2", categoryId: "2", amount: "420", expenseDate: today,
    description: "مستلزمات تعقيم وبطاريات (بانتظار الاعتماد)", beneficiary: "مورد مستلزمات تجريبي", documentNumber: "", taxAmount: "",
  });
  await createExpense(fdb, "6", {
    requestId: randomUUID(), branchId: "3", categoryId: "3", amount: "185", expenseDate: today,
    description: "توصيل قوالب أذن من المعمل (بانتظار الاعتماد)", beneficiary: "مندوب توصيل تجريبي", documentNumber: "", taxAmount: "",
  });
  const approvedPendingPay = await createExpense(fdb, "1", {
    requestId: randomUUID(), branchId: "1", categoryId: "1", amount: "1250", expenseDate: today,
    description: "فاتورة كهرباء ومياه الفرع (بانتظار الصرف)", beneficiary: "شركة المرافق", documentNumber: "INV-104", taxAmount: "",
  });
  await approveExpense(fdb, "2", { requestId: randomUUID(), expenseId: approvedPendingPay.id, expectedRevision: "1" });

  await requestCashCount(fdb, "2", {
    requestId: randomUUID(), accountId: vault1.id, expectedBalance: "34200", countedAmount: "34200",
    reason: "جرد دوري لخزنة العريش", actuallyCounted: true,
  }, today);

  await requestSettlement(fdb, "5", {
    requestId: randomUUID(),
    accountId: custody2.id,
    expectedBalance: "800",
    countedAmount: "2680",
    reason: "تسليم إيراد اليوم من عهدة الفرع",
    actuallyCounted: true,
  });

  return client;
}

state.__financeLabPrisma ??= initialize();
export const prisma = await state.__financeLabPrisma;
