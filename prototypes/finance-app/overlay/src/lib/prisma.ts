/** TEST-ONLY replacement in a disposable copy of the app. It cannot connect to
 * an external database. Never copy this module to the production application. */
import "server-only";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { join } from "node:path";
import bcrypt from "bcryptjs";
import { PGlite } from "@electric-sql/pglite";
import { PrismaPGlite } from "pglite-prisma-adapter";
import type { PrismaClient } from "@prisma/client";
import { PrismaClient as TestClient } from "../../.finance-client";
import { createCommerceSale, returnCommerceSale } from "./commerce-operations";

const state = globalThis as typeof globalThis & { __financeLabPrisma?: Promise<PrismaClient> };
async function initialize(): Promise<PrismaClient> {
  const root = process.env.FINANCE_LAB_PROJECT_DIR;
  if (process.env.NODE_ENV !== "development" || process.env.FINANCE_LAB_ONLY !== "disposable-in-memory" || !root) {
    throw new Error("The finance lab can only run in its disposable development copy.");
  }
  // No URL or filesystem data directory: all public and finance_lab tables live
  // in one fresh in-memory database, solely for fictional transactions.
  const pg = new PGlite();
  for (const file of ["tests/fixtures/inventory-baseline.sql", "prisma/manual-inventory-upgrade.sql", "prisma/manual-receiving-upgrade.sql", "prisma/manual-commerce-upgrade.sql"]) {
    await pg.exec(await readFile(join(root, file), "utf8"));
  }
  await pg.exec(`
    CREATE TYPE "AuthAttemptResult" AS ENUM ('SUCCESS','FAILED','THROTTLED','PASSWORD_CHANGE_SUCCESS','PASSWORD_CHANGE_FAILED','PASSWORD_RESET');
    CREATE TABLE auth_sessions (id VARCHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at TIMESTAMPTZ NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE login_attempts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, identifier_hash CHAR(64) NOT NULL, user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, result "AuthAttemptResult" NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE login_throttles (key CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 0, window_started_at TIMESTAMPTZ NOT NULL, locked_until TIMESTAMPTZ, updated_at TIMESTAMPTZ NOT NULL);
    CREATE TABLE expense_categories (id SERIAL PRIMARY KEY, code VARCHAR(30) UNIQUE NOT NULL, name_ar VARCHAR(120) NOT NULL, is_active BOOLEAN NOT NULL DEFAULT true);
    INSERT INTO expense_categories(code,name_ar) VALUES('LAB','بند وهمي');
    INSERT INTO tax_rates(id,code,name_ar,rate,kind,is_active,effective_from) VALUES (3,'EXEMPT','إعفاء وهمي',0,'EXEMPT',true,'2020-01-01');
    UPDATE products SET is_active=false;
    UPDATE products SET name_ar='بطارية للتجربة',sale_price=100,tax_rate_id=3,is_active=true WHERE id=2;
    UPDATE products SET name_ar='خدمة للتجربة',sale_price=250,tax_rate_id=3,is_active=true WHERE id=3;
    INSERT INTO branches(id,code,name_ar,invoice_prefix) VALUES (3,'B3','فرع تجريبي موقوف','B3');
    SELECT setval(pg_get_serial_sequence('branches','id'),3,true);
    INSERT INTO warehouses(id,branch_id,code,name_ar,is_active) VALUES (4,3,'W3','مستودع تجريبي للفرع الموقوف',TRUE);
    SELECT setval(pg_get_serial_sequence('warehouses','id'),4,true);
    INSERT INTO stock_levels(warehouse_id,product_id,qty_on_hand,avg_cost) VALUES (1,2,100,40),(2,2,100,40),(4,2,100,40);
    INSERT INTO users(id,branch_id,role_code,full_name,email,password_hash,status,must_change_password) VALUES
      (5,2,'CS_AGENT','موظف فرع آخر وهمي','staff2@example.test','placeholder','ACTIVE',false),
      (6,1,'CS_AGENT','موظف إضافي وهمي','staff3@example.test','placeholder','ACTIVE',false),
      (7,3,'CS_AGENT','موظف الفرع الموقوف الوهمي','staff-stop@example.test','placeholder','ACTIVE',false);
    SELECT setval(pg_get_serial_sequence('users','id'),7,true);
  `);
  const password = await bcrypt.hash("DemoOnly-2026!", 10);
  await pg.query("UPDATE users SET password_hash=$1, must_change_password=false", [password]);
  await pg.exec("SET selahtone.finance_lab_test_only = 'yes'");
  await pg.exec(await readFile(join(root, "prototypes/finance-engine/schema.test-only.sql"), "utf8"));
  await pg.exec(`
    INSERT INTO finance_lab.branches(id,name_ar,is_active) SELECT id,name_ar,is_active FROM public.branches;
    INSERT INTO finance_lab.users(id,branch_id,role_code,status,must_change_password,full_name)
      SELECT id,branch_id,role_code::text,status::text,must_change_password,full_name FROM public.users;
    INSERT INTO finance_lab.categories(name_ar,created_by) VALUES ('مستلزمات تجريبية',1),('نقل تجريبي',1);
    INSERT INTO finance_lab.accounts(branch_id,kind,holder_id,opening_amount,opening_date,opened_by) VALUES
      (1,'VAULT',NULL,5000,'2020-01-01',1),(1,'CUSTODY',3,800,'2020-01-01',1),
      (2,'VAULT',NULL,2500,'2020-01-01',1),(2,'CUSTODY',5,300,'2020-01-01',1),
      (3,'VAULT',NULL,500,'2020-01-01',1),(3,'CUSTODY',7,50,'2020-01-01',1);
  `);
  const client = new TestClient({ adapter: new PrismaPGlite(pg) as never }) as unknown as PrismaClient;
  // A stopped branch has two pre-existing FICTIONAL invoices so a visitor can
  // try collecting a debt and recording a refund. Use the same test operations
  // as the UI while the branch is active, then stop it in both lab schemas.
  const demoSale = (customerName: string, initialPayment: string) => ({
    requestId: randomUUID(), warehouseId: "4", customerName, customerPhone: "01000000000", discount: "0", initialPayment, method: "CARD",
    lines: [{ productId: "2", quantity: "1", serialIds: [], expectedUnitPrice: "100", expectedTaxRateId: 3, expectedTaxKind: "EXEMPT", expectedTaxRate: "0" }],
  });
  await createCommerceSale(client, 1n, demoSale("عميل تحصيل وهمي — فرع موقوف", "40"));
  const refundDemo = await createCommerceSale(client, 1n, demoSale("عميل رد وهمي — فرع موقوف", "100"));
  await returnCommerceSale(client, 1n, { requestId: randomUUID(), saleId: refundDemo.id, cancel: true, accepted: true, lines: [] });
  // These are entirely fictitious *prior* invoices: dates precede the 2020
  // opening count so the historical collection/refund example is coherent.
  await pg.exec(`UPDATE public.commerce_sales SET created_at='2019-12-20 10:00:00+00',
      cancelled_at=CASE WHEN cancelled_at IS NULL THEN NULL ELSE '2019-12-25 10:00:00+00'::timestamptz END WHERE branch_id=3;
    UPDATE public.commerce_collections SET created_at='2019-12-20 10:00:00+00' WHERE sale_id IN (SELECT id FROM public.commerce_sales WHERE branch_id=3);
    UPDATE public.commerce_returns SET created_at='2019-12-25 10:00:00+00' WHERE sale_id IN (SELECT id FROM public.commerce_sales WHERE branch_id=3);`);
  await pg.exec("UPDATE public.branches SET is_active=false WHERE id=3; UPDATE finance_lab.branches SET is_active=false WHERE id=3");
  return client;
}
state.__financeLabPrisma ??= initialize();
export const prisma = await state.__financeLabPrisma;
