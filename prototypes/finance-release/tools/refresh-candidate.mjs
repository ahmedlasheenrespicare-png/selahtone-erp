#!/usr/bin/env node
/** Regenerates and re-stamps the DISPOSABLE release candidate from the lab schema.
 * It is a review aid: it shows exactly how the candidate was derived and keeps
 * its sha256 literal in sync. It never touches a database and never runs SQL.
 *
 *   node prototypes/finance-release/tools/refresh-candidate.mjs
 *
 * Re-run it after editing the lab schema, then re-run
 * `npm run check:finance:release-candidate` and review the resulting diff.
 * The output is still a TEST-ONLY draft, not an approved production migration. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const out = "prototypes/finance-release/release-candidate.test-only.sql";
const labPath = "prototypes/finance-engine/schema.test-only.sql";
let src = readFileSync(labPath, "utf8");
const cut = (re, label) => { const next = src.replace(re, ""); if (next === src) throw new Error(`lab schema shape changed: ${label}`); src = next; };

cut(/^DO \$\$[\s\S]*?END \$\$;\n\n/m, "lab opt-in guard");
cut(/CREATE SCHEMA finance_lab;\n\n/, "lab schema line");
for (const t of ["branches", "users", "categories", "attachment_quota", "expense_attachments"]) {
  cut(new RegExp(String.raw`CREATE TABLE finance_lab\.${t} \([\s\S]*?\n\);\n\n?`), `lab table ${t}`);
}
cut(/CREATE UNIQUE INDEX finance_lab_categories_name_key[^;]*;\n\n?/, "lab category index");
cut(/INSERT INTO finance_lab\.attachment_quota\(singleton\) VALUES \(1\);\n/, "lab quota row");
cut(/-- Disposable upload experiment ONLY[\s\S]*?-- The quota protects this public demo from unlimited accumulated uploads\.\n/, "lab attachment comment");
cut(/-- TEST-ONLY FINANCE LAB[\s\S]*?Never run it on Neon or any database containing actual business data\.\n/, "lab header comment");
cut(/-- Stand-ins for the real application tables[^\n]*\n/, "lab stand-in comment");
src = src
  .replaceAll("REFERENCES finance_lab.categories(id)", "REFERENCES public.expense_categories(id)")
  .replaceAll("REFERENCES finance_lab.branches(id)", "REFERENCES public.branches(id)")
  .replaceAll("REFERENCES finance_lab.users(id)", "REFERENCES public.users(id)")
  .replaceAll("finance_lab.", "finance.")
  .replaceAll("finance_lab_", "finance_")
  .replace("-- The lab commerce bridge writes", "-- The commerce bridge writes");
if (src.includes("The lab commerce bridge")) throw new Error("lab bridge comment not rewritten");
src = src.replace("category_id BIGINT NOT NULL REFERENCES public.expense_categories(id),", "category_id INTEGER NOT NULL REFERENCES public.expense_categories(id),");
if (!src.includes("category_id INTEGER NOT NULL REFERENCES public.expense_categories(id)")) throw new Error("expense category column not retyped");
src = src
  .replace(/^CREATE TABLE /gm, "CREATE TABLE IF NOT EXISTS ")
  .replace(/^CREATE UNIQUE INDEX /gm, "CREATE UNIQUE INDEX IF NOT EXISTS ")
  .replace(/^CREATE INDEX /gm, "CREATE INDEX IF NOT EXISTS ");
// The lab adds one payment column with ALTER; keep a replay-safe guarded version.
const alterGuard = `DO $guard$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='finance' AND table_name='payments' AND column_name='after_cash_count_id') THEN
    ALTER TABLE finance.payments ADD COLUMN after_cash_count_id BIGINT REFERENCES finance.cash_counts(id);
    ALTER TABLE finance.payments ADD CONSTRAINT finance_payment_count_order
      CHECK (after_cash_count_id IS NULL OR (method='CASH' AND NOT historical));
  END IF;
END $guard$;
`;
const alterBlock = /-- A same-day payment may be posted[\s\S]*?CHECK \(after_cash_count_id IS NULL OR \(method='CASH' AND NOT historical\)\);\n/;
if (!alterBlock.test(src)) throw new Error("payment alter block not found");
src = src.replace(alterBlock, alterGuard);

const zeros = "0".repeat(64);
const header = `-- TEST-ONLY FINANCE RELEASE CANDIDATE — NOT AN APPROVED PRODUCTION MIGRATION.
-- Never run this on Neon or a database containing business data. It is a review
-- draft: it references the real public tables, keeps legacy rows untouched, and
-- deliberately omits attachments, deferred COMMIT checks, GRANTs and RLS.
--
-- sha256: ${zeros}
--
-- Excluded on purpose, each needing its own approved design and test:
--   * expense attachments: the storage choice (Neon Object Storage) is not
--     enabled, and the effective Netlify request limit for a base64 binary
--     is about 4.5 MB, below the 5 MB requirement.
--   * deferred COMMIT constraints: blocked until the production engine's
--     connection lifecycle after a failed COMMIT is tested.
--   * GRANTs, RLS and ownership: the application database role is not verified.
--   * converting or backfilling legacy expenses and journal entries.
-- Generated by prototypes/finance-release/tools/refresh-candidate.mjs; review the diff.
DO $$
BEGIN
  IF current_setting('selahtone.finance_release_candidate_test_only', true) IS DISTINCT FROM 'yes' THEN
    RAISE EXCEPTION 'finance release candidate requires an explicitly opted-in disposable database';
  END IF;
END $$;

-- Preconditions on the audited baseline. They fail closed before any object is
-- created; this file never ALTERs or rewrites legacy tables or their rows.
DO $$
DECLARE missing TEXT;
BEGIN
  SELECT string_agg(obj, ', ') INTO missing FROM (VALUES ('public.branches'),('public.users'),('public.expense_categories')) AS v(obj)
   WHERE to_regclass(obj) IS NULL;
  IF missing IS NOT NULL THEN RAISE EXCEPTION 'baseline object missing: %', missing; END IF;
  IF (SELECT count(*) FROM information_schema.columns WHERE table_schema='public' AND table_name='expense_categories'
        AND column_name IN ('id','code','name_ar','is_active')) <> 4 THEN
    RAISE EXCEPTION 'public.expense_categories shape changed';
  END IF;
  IF to_regnamespace('finance') IS NOT NULL AND to_regclass('finance_release.migrations') IS NULL THEN
    RAISE EXCEPTION 'schema finance already exists without the migration ledger';
  END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS finance;
CREATE SCHEMA IF NOT EXISTS finance_release;
CREATE TABLE IF NOT EXISTS finance_release.migrations (
  name TEXT PRIMARY KEY,
  checksum CHAR(64) NOT NULL,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  applied_by NAME NOT NULL DEFAULT session_user
);

`;
const footer = `
-- Record the applied script. A replay with the same checksum is a no-op; the
-- same script name with a different checksum is refused instead of diverging.
-- The checksum covers this file with the literal below replaced by zeros, so it
-- stays verifiable; the tests recompute it the same way.
DO $$
DECLARE previous CHAR(64);
BEGIN
  SELECT checksum INTO previous FROM finance_release.migrations WHERE name='finance_release_candidate';
  IF previous IS NOT NULL AND previous <> '${zeros}' THEN
    RAISE EXCEPTION 'finance release candidate checksum changed since it was applied';
  END IF;
  INSERT INTO finance_release.migrations(name,checksum) VALUES ('finance_release_candidate','${zeros}')
    ON CONFLICT (name) DO NOTHING;
END $$;
`;
let body = header + src.trimEnd() + "\n" + footer;
const count = (body.match(new RegExp(zeros, "g")) ?? []).length;
if (count !== 3) throw new Error(`expected 3 checksum placeholders, found ${count}`);
const digest = createHash("sha256").update(body).digest("hex");
body = body.split(zeros).join(digest);
writeFileSync(out, body);
console.log(`wrote ${out} (${body.length} bytes) sha256 ${digest}`);
