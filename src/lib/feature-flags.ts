/**
 * وحدة التعليمات (feature flags) المشتركة.
 *
 * قاعدة ثابتة في هذا المشروع: كل تعطيل اختيار صريح لا ضمني. المخزون معطّل
 * افتراضيًا لأن سير العمل الفعلي في الشركة لا يستخدم مخزونًا ولا مستودعات:
 * الموظف يسجّل البيع بأصناف فنية ويكتب السعر بنفسه. إخفاء القائمة وحده لا
 * يكفي، بل يمنع الخادم أيضًا فتح شاشات المخزون وكتابة أي حركة مخزون.
 *
 * إعادة التشغيل: ضبط المتغيّر INVENTORY_ENABLED=true في بيئة النشر فقط،
 * وبقرار منفصل بعد مراجعة. البيانات القديمة لا تُحذف ولا تُعدَّل عند التعطيل.
 */
export function inventoryEnabled(): boolean {
  return process.env.INVENTORY_ENABLED === "true";
}
