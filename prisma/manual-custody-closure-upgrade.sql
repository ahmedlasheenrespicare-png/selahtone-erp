-- هجرة إنتاج واجبة قبل تشغيل «إقفال العهدة».
--
-- لم يكن في الجدول ما يميّز العهدة المغلقة، فمن أخذ إجازة أو ترك العمل بقيت
-- عهدته تُحصى في «العهد القائمة» وتظهر له في «عهدتي»، وإن فُتحت له عهدة جديدة
-- صار له حسابان ولا يُعرف أيهما يُقرأ.
--
-- وعمود الإقفال لا يحذف شيئًا: فالحساب وسجل حركاته وتسوياته تبقى كلها، وكل ما
-- يتغيّر أنه لم يعد عهدة قائمة. والعمودان فارغان (NULL) لكل حساب مفتوح، فلا
-- يحتاج هذا الملف إلى تعبئة بيانات بعد تشغيله.
ALTER TABLE finance.accounts
  ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS closed_by BIGINT REFERENCES public.users(id);
