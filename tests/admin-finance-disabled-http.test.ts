const forms = (html: string) => [...html.matchAll(/<form\b[\s\S]*?<\/form>/g)].map(m => m[0]);
function hidden(form: string): FormData {
  const data = new FormData();
  for (const [tag] of form.matchAll(/<input\b[^>]*>/g)) {
    if (!tag.includes('type="hidden"')) continue;
    const name = tag.match(/name="([^"]+)"/)?.[1], value = tag.match(/value="([^"]*)"/)?.[1] ?? "";
    if (name) data.set(name, value.replaceAll("&quot;", '"').replaceAll("&amp;", "&"));
  }
  return data;
}
async function port(): Promise<number> {
  const server = createServer(); await new Promise<void>((resolve,reject) => server.once("error",reject).listen(0,"127.0.0.1",resolve));
  const address = server.address(); if (!address || typeof address === "string") throw new Error("missing port");
  await new Promise<void>((resolve,reject) => server.close(err => err ? reject(err) : resolve())); return address.port;
}
async function stop(child: ChildProcess) {
  if (child.exitCode !== null || child.signalCode !== null) return;
  const exited = new Promise<void>(resolve => child.once("exit",() => resolve())); child.kill("SIGTERM");
  await Promise.race([exited,new Promise<void>(resolve => { setTimeout(resolve,5000).unref(); })]);
  if (child.exitCode === null && child.signalCode === null) { child.kill("SIGKILL"); await exited; }
}
function actionId(name: string): string {
  // Read the dev build manifest generated by this very server. Never hardcode
  // action IDs: Next can change them across builds or repository paths.
  const page = readFileSync(join(root,".next/server/app/(app)/admin/page.js"),"utf8");
  const decoded = decodeURIComponent(page.replace(/%(?![0-9a-f]{2})/gi, "%25"));
  const id = decoded.match(new RegExp(`"id":"([0-9a-f]+)","exportedName":"${name}"`))?.[1];
  assert.ok(id, `missing Next action id ${name}`); return id;
}

