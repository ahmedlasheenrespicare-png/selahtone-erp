// LOCAL PGlite preview bootstrap (NOT for production).
// Generates CREATE TABLE / ENUM DDL directly from Prisma's DMMF because the
// migration engines cannot run in this sandbox (binaries.prisma.sh unreachable).
// Usage: node scripts/local-pglite-ddl.cjs [out.sql]
const fs=require('node:fs');
const path=require('node:path');
const { Prisma } = require(path.join(__dirname,'..','node_modules','@prisma/client'));
const d = Prisma.dmmf.datamodel;
const models = d.models;
const byName = Object.fromEntries(models.map(m => [m.name, m]));
const enumNames = new Set(d.enums.map(e => e.name));
const qi = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const colMap = (m) => Object.fromEntries(m.fields.filter(f => f.kind !== 'object').map(f => [f.name, f.dbName ?? f.name]));

let ddl = '-- AUTO-GENERATED FROM DMMF (local PGlite preview bootstrap) — not for production\n';
for (const e of d.enums) {
  const vals = e.values.map(v => '\'' + (v.dbName ?? v.name) + '\'').join(', ');
  ddl += 'DROP TYPE IF EXISTS ' + qi(e.name) + ' CASCADE;\nCREATE TYPE ' + qi(e.name) + ' AS ENUM (' + vals + ');\n';
}
const isDateOnly = (f) => Array.isArray(f.nativeType) && f.nativeType[0] === 'Date';
function colType(f) {
  const nt = f.nativeType;
  if (nt && nt.length) {
    const args = nt.slice(1).flat(2).filter(a => a !== '' && a != null).map(Number);
    switch (nt[0]) {
      case 'VarChar': return `varchar(${args[0]})`;
      case 'Char': return `char(${args[0]})`;
      case 'SmallInt': return 'smallint';
      case 'Date': return 'date';
      case 'Timestamptz': return 'timestamptz';
      case 'Uuid': return 'uuid';
      case 'Decimal': return `numeric(${args[0] ?? 14},${args[1] ?? 2})`;
    }
  }
  switch (f.type) {
    case 'String': return 'text';
    case 'Int': return 'integer';
    case 'BigInt': return 'bigint';
    case 'Boolean': return 'boolean';
    case 'DateTime': return 'timestamptz';
    case 'Decimal': return 'numeric(14,2)';
    case 'Json': return 'jsonb';
    default:
      if (enumNames.has(f.type)) return qi(f.type);
      throw new Error('unmapped type: ' + f.type + '.' + f.name);
  }
}
const isIdentity = (f) => f.default && typeof f.default === 'object' && f.default.name === 'autoincrement';
function defaultExpr(f) {
  const dfl = f.default;
  if (dfl === undefined) return null;
  if (typeof dfl === 'boolean' || typeof dfl === 'number') return String(dfl);
  if (typeof dfl === 'string') {
    if (dfl === 'true' || dfl === 'false') return dfl;
    if (/^-?\d+$/.test(dfl)) return dfl;
    if (dfl === '{}') return "'{}'::jsonb";
    return `'${dfl.replace(/'/g, "''")}'`;
  }
  if (typeof dfl === 'object') {
    if (dfl.name === 'now') return isDateOnly(f) ? 'CURRENT_DATE' : 'now()';
    if (dfl.name === 'dbgenerated' && Array.isArray(dfl.args)) return String(dfl.args[0]);
  }
  return null;
}
for (const m of models) {
  const cols = [];
  for (const f of m.fields) {
    if (f.kind === 'object') continue;
    let parts = qi(f.dbName ?? f.name) + ' ';
    if (isIdentity(f)) {
      parts += (f.type === 'BigInt' ? 'bigint' : f.type === 'Int' ? 'integer' : colType(f)) + ' GENERATED BY DEFAULT AS IDENTITY';
    } else {
      parts += colType(f);
    }
    if (f.isId) parts += ' PRIMARY KEY';
    if (f.isRequired) parts += ' NOT NULL';
    const def = defaultExpr(f);
    if (def) parts += ' DEFAULT ' + def;
    else if (f.isUpdatedAt) parts += ' DEFAULT now()';
    if (f.isUnique && !f.isId) parts += ' UNIQUE';
    cols.push(parts);
  }
  const seen = new Set();
  for (const arr of (m.uniqueFields ?? [])) {
    const fields = arr.map(n => { const mf = m.fields.find(x => x.name === n); return qi(mf.dbName ?? mf.name); });
    const sig = fields.join(',');
    if (seen.has(sig)) continue; seen.add(sig);
    cols.push('UNIQUE (' + sig + ')');
  }
  ddl += 'CREATE TABLE ' + qi(m.dbName) + ' (\n  ' + cols.join(',\n  ') + '\n);\n';
}
for (const m of models) {
  const cm = colMap(m);
  for (const f of m.fields) {
    if (f.kind !== 'object' || f.isList || !f.relationFromFields || f.relationFromFields.length === 0) continue;
    const refM = byName[f.type];
    if (!refM) { console.error('skip FK (unknown target):', m.name, f.name, f.type); continue; }
    const cols = f.relationFromFields.map(n => qi(cm[n]));
    const refCm = colMap(refM);
    const refCols = (f.relationToFields ?? ['id']).map(n => qi(refCm[n] ?? n));
    const onDel = { Cascade: 'CASCADE', Restrict: 'RESTRICT', SetNull: 'SET NULL', NoAction: 'NO ACTION' }[f.relationOnDelete] ?? 'NO ACTION';
    ddl += 'ALTER TABLE ' + qi(m.dbName) + ' ADD CONSTRAINT ' + qi('fk_' + m.dbName + '_' + f.name) + ' FOREIGN KEY (' + cols.join(', ') + ') REFERENCES ' + qi(refM.dbName) + ' (' + refCols.join(', ') + ') ON DELETE ' + onDel + ';\n';
  }
}
// The access-control store is a manual production upgrade, but a fresh local
// preview must include it so current write guards can run without extra steps.
ddl += `CREATE TABLE "access_control" (
  "subject_kind" varchar(8) NOT NULL CHECK (subject_kind IN ('role','user')),
  "subject" varchar(64) NOT NULL,
  "key" varchar(130) NOT NULL,
  "allowed" boolean NOT NULL,
  "updated_by" varchar(64),
  "updated_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("subject_kind","subject","key")
);
CREATE INDEX "access_control_key" ON "access_control" ("key");
`;
function buildDdl(){ return ddl; }
module.exports = { buildDdl };
if (require.main === module) {
  const out = process.argv[2];
  const sql = buildDdl();
  const lines = sql.split('\n').filter(Boolean).length;
  if (out) { fs.writeFileSync(out, sql); console.log('DDL written to', out, '—', lines, 'statements/lines'); }
  else process.stdout.write(sql);
}
